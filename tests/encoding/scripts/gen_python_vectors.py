#!/usr/bin/env python3
"""为 Go2Cpp `encoding` 模块生成 Python 对拍向量。

用途
----
`tests/encoding/test_random.cpp` 读取 `tests/encoding/testdata/python_vectors.txt`，
逐条验证本模块的 base64 / hex 输出与 Python 标准库完全一致。ctest 运行时不依赖
Python；只有需要重新生成/扩充向量时才执行本脚本。

向量来源（Python 3.12.3 标准库，官方实现）：
  - ``base64.b64encode``            -> b64std
  - ``base64.urlsafe_b64encode``    -> b64url
  - 上面两者去掉 ``=``               -> b64rawstd / b64rawurl
  - ``binascii.hexlify``            -> hex

文件格式（制表符分隔，保留空字段）::

    <kind>\t<输入字节的十六进制>\t<期望输出>

空输入对应两个空字段（行尾两个制表符）。`#` 开头为注释。

运行::

    python3 tests/encoding/scripts/gen_python_vectors.py

脚本使用固定种子（20261018），重复执行结果完全一致。
"""

import base64
import binascii
import pathlib
import random
import sys

SEED = 20261018
OUTPUT = (
    pathlib.Path(__file__).resolve().parent.parent
    / "testdata"
    / "python_vectors.txt"
)


def build_vectors() -> list[bytes]:
    rng = random.Random(SEED)

    def random_bytes(n: int) -> bytes:
        return bytes(rng.getrandbits(8) for _ in range(n))

    # 固定长度：覆盖 0..31，以及 base64 三种长度余数与常见边界。
    lengths = list(range(0, 32)) + [
        63, 64, 65, 127, 128, 129, 255, 256, 257, 511, 512, 513, 1000,
    ]
    vectors = [random_bytes(n) for n in lengths]

    # 随机长度（0..1024）。
    for _ in range(16):
        vectors.append(random_bytes(rng.randrange(0, 1025)))

    # 特殊字节模式：全 0、全 0xff、0..255 全字节表。
    vectors.append(bytes(17))
    vectors.append(b"\xff" * 17)
    vectors.append(bytes(range(256)))
    return vectors


def main() -> int:
    vectors = build_vectors()
    lines = [
        "# Go2Cpp encoding module: Python reference vectors",
        "# generated by tests/encoding/scripts/gen_python_vectors.py",
        "# Python: base64.b64encode / base64.urlsafe_b64encode / binascii.hexlify",
        "# format: <kind>\\t<hex input>\\t<expected output>",
    ]
    total_bytes = 0
    for data in vectors:
        hex_input = binascii.hexlify(data).decode("ascii")
        std = base64.b64encode(data).decode("ascii")
        url = base64.urlsafe_b64encode(data).decode("ascii")
        raw_std = std.rstrip("=")
        raw_url = url.rstrip("=")
        rows = (
            ("b64std", std),
            ("b64url", url),
            ("b64rawstd", raw_std),
            ("b64rawurl", raw_url),
            ("hex", hex_input),
        )
        for kind, expected in rows:
            lines.append(f"{kind}\t{hex_input}\t{expected}")
        total_bytes += len(data)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(
        f"wrote {len(lines) - 4} vectors for {len(vectors)} inputs "
        f"({total_bytes} input bytes) to {OUTPUT}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
