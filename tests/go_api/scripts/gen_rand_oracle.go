// gen_rand_oracle.go 生成 crypto/rand 对拍数据（由 tests/go_api/test_go_crypto_rand.cpp 读取）。
//
// 覆盖两件事：
//  1. BigInt 的十进制/十六进制/字节转换与 `ProbablyPrime` 判定——输入由同一个
//     xorshift64* PRNG 生成，C++ 侧复现同样的候选数并逐项比对；
//  2. `crypto/rand.Int` 的拒绝采样结果——Go 侧用 PRNG 包装成 io.Reader，
//     C++ 侧用同一 PRNG 作为 Source，两边应得到**完全相同**的值。
//
// `crypto/rand.Prime` 不做逐值对拍：Go 1.26 起它内部调用
// `crypto/internal/rand.CustomReader`，默认**忽略**传入的 reader 改用全局
// DRBG；即使设置 GODEBUG=cryptocustomrand=1，`randutil.MaybeReadByte` 也会
// 以 50% 概率多读一个字节，导致候选序列不可复现。C++ 侧改为验证位长、
// 最高两位、奇偶与素性。
//
// 用法：go run ./gen_rand_oracle.go <输出文件>
package main

import (
	"bufio"
	"crypto/rand"
	"fmt"
	"math/big"
	"os"
	"runtime"
)

const prngSeed uint64 = 0x243F6A8885A308D3

type prng struct{ state uint64 }

func (p *prng) next() uint64 {
	x := p.state
	x ^= x >> 12
	x ^= x << 25
	x ^= x >> 27
	p.state = x
	return x * 2685821657736338717
}

// prngReader 把 PRNG 包成 io.Reader：每次返回请求的字节数，字节序与 C++ 侧一致。
type prngReader struct{ source *prng }

func (r *prngReader) Read(buffer []byte) (int, error) {
	for offset := 0; offset < len(buffer); {
		word := r.source.next()
		for index := 0; index < 8 && offset < len(buffer); index++ {
			buffer[offset] = byte(word >> (8 * index))
			offset++
		}
	}
	return len(buffer), nil
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen_rand_oracle <output>")
		os.Exit(2)
	}
	file, err := os.Create(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer file.Close()
	writer := bufio.NewWriter(file)
	defer writer.Flush()

	fmt.Fprintf(writer, "# go-rand-oracle v1\n")
	fmt.Fprintf(writer, "# generated by %s\n", runtime.Version())
	fmt.Fprintf(writer, "seed 0x%016x\n", prngSeed)

	// 1) 素性/进制转换：每种位长 40 个候选。
	random := &prng{state: prngSeed}
	bitSizes := []int{2, 3, 8, 16, 32, 64, 96, 128, 192, 256}
	for _, bits := range bitSizes {
		for sample := 0; sample < 40; sample++ {
			value := new(big.Int)
			bytes := make([]byte, (bits+7)/8)
			for index := range bytes {
				bytes[index] = byte(random.next())
			}
			value.SetBytes(bytes)
			if value.Sign() == 0 {
				value.SetInt64(1)
			}
			// 去掉超出位长的部分，保证测试侧可以按位长重建。
			excess := len(bytes)*8 - bits
			value.Rsh(value, uint(excess))
			fmt.Fprintf(writer, "prime %d %s %t\n", bits, value.Text(16),
				value.ProbablyPrime(20))
		}
	}

	// 2) Int：确定性 reader + 固定上界。
	//
	// 注意：`crypto/rand.Int` 直接使用传入的 reader（不像 `Prime` 那样经过
	// `rand.CustomReader`），因此可以逐值对拍。
	intSource := &prngReader{source: &prng{state: prngSeed ^ 0xA5A5A5A5A5A5A5A5}}
	maxima := []string{"1", "2", "3", "7", "255", "256", "257", "65535",
		"65536", "1000000", "4294967295", "4294967296",
		"18446744073709551615", "18446744073709551616",
		"340282366920938463463374607431768211455"}
	for _, text := range maxima {
		maximum, _ := new(big.Int).SetString(text, 10)
		for sample := 0; sample < 5; sample++ {
			value, err := rand.Int(intSource, maximum)
			if err != nil {
				fmt.Fprintf(writer, "int %s error\n", text)
				continue
			}
			fmt.Fprintf(writer, "int %s %s\n", text, value.Text(16))
		}
	}
}
