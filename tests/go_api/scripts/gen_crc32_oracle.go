// gen_crc32_oracle.go 生成 CRC-32 对拍数据（由 tests/go_api/test_go_crc32.cpp 读取）。
//
// 数据源是一个**确定性** xorshift64* PRNG（种子写在文件头），C++ 测试用完全
// 相同的算法复现同一段 1e6 字节，再与 Go 标准库 hash/crc32 的结果逐项比对。
// 这样对拍是「同一输入 + 两个独立实现」，而不是「同一实现算两遍」。
//
// 用法：go run ./gen_crc32_oracle.go <输出文件>
package main

import (
	"bufio"
	"fmt"
	"hash/crc32"
	"os"
	"runtime"
)

const (
	prngSeed  uint64 = 0x9E3779B97F4A7C15
	chunkSize        = 100_000
	chunkCount       = 10
)

// xorshift64*：与 C++ 测试里的 Prng 类逐位一致。
type prng struct{ state uint64 }

func (p *prng) next() uint64 {
	x := p.state
	x ^= x >> 12
	x ^= x << 25
	x ^= x >> 27
	p.state = x
	return x * 2685821657736338717
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen_crc32_oracle <output>")
		os.Exit(2)
	}
	file, err := os.Create(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer file.Close()
	writer := bufio.NewWriter(file)
	defer writer.Flush()

	fmt.Fprintf(writer, "# go-crc32-oracle v1\n")
	fmt.Fprintf(writer, "# generated by %s\n", runtime.Version())
	fmt.Fprintf(writer, "seed 0x%016x\n", prngSeed)
	fmt.Fprintf(writer, "chunk_size %d\n", chunkSize)
	fmt.Fprintf(writer, "chunk_count %d\n", chunkCount)

	random := &prng{state: prngSeed}
	castagnoli := crc32.MakeTable(crc32.Castagnoli)
	koopman := crc32.MakeTable(crc32.Koopman)

	all := make([]byte, 0, chunkSize*chunkCount)
	for chunk := 0; chunk < chunkCount; chunk++ {
		data := make([]byte, chunkSize)
		for offset := 0; offset+8 <= chunkSize; offset += 8 {
			word := random.next()
			for index := 0; index < 8; index++ {
				data[offset+index] = byte(word >> (8 * index))
			}
		}
		all = append(all, data...)
		fmt.Fprintf(writer, "chunk %d %08x %08x %08x\n", chunk,
			crc32.ChecksumIEEE(data),
			crc32.Checksum(data, castagnoli),
			crc32.Checksum(data, koopman))
	}
	fmt.Fprintf(writer, "total %08x %08x %08x\n",
		crc32.ChecksumIEEE(all),
		crc32.Checksum(all, castagnoli),
		crc32.Checksum(all, koopman))
	fmt.Fprintf(writer, "bytes %d\n", len(all))
}
