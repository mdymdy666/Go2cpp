/**
 * @file douyin_tag.hpp
 * @brief 抖音 demo 的话题标签提取：把标题解析成 `#话题` 列表。
 *
 * @details 规则只有两条，按优先级：
 *          1. 标题里显式写了 `#tag`，以显式标签为准（发布者意图优先）；
 *          2. 否则查内置「标题关键词 -> 话题」映射表（覆盖 demo 的 20 条
 *             历史视频，它们发布时还没有话题功能）。
 *          不做数据库表：视频量级是 demo（几十条），查询时实时提取即可，
 *          避免「标题改了标签不同步」的一致性问题。
 *
 * @author douyin demo
 * @date 2026-11-04
 * @copyright MIT License
 */

#pragma once

#include <string>
#include <vector>

namespace douyin {

/**
 * @brief 从视频标题提取话题列表。
 *
 * @param title [in] 视频标题（UTF-8）——借用，调用期间有效；可为空串。
 *
 * @return 去重后的话题（不含 `#`，按出现/命中顺序）；无任何话题时返回空
 *         向量——调用方**必须**按「没有话题」处理，不要伪造默认标签。
 *
 * ## 定位
 * 话题聚合的唯一提取点：视频 JSON 的 `tags`、热门话题、话题详情页都
 * 走这里。错了会怎样：标题里的 `#` 被当成正文、或不同接口算出不同标签，
 * 话题页与卡片展示会对不上。
 *
 * ## 步骤
 * step1. 扫描 UTF-8 标题，遇 `#` 收集后续码点，遇到空白/标点/下一个 `#`
 *        终止；这一步保证 `#爬山，云海` 不会把逗号吃进标签；
 * step2. 若拿到至少一个显式标签，去重后返回（最多 5 个）；
 * step3. 否则按关键词表做子串匹配，去重后返回（最多 3 个）。
 *
 * ## 并发/失败语义
 * - 调用约束：纯函数，无状态，可在任意线程调用；
 * - 原子性：不涉及共享可变状态；
 * - 失败语义：不抛异常（内部只做字符串操作）；
 * - 不变量：返回的每个标签非空、不含 `#`、长度 <= 60 字节。
 */
std::vector<std::string> ExtractTags(const std::string& title);

}  // namespace douyin
